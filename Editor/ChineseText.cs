    static Dictionary<string, int> index_;

    static void Ensure()
    {
        if (index_ != null) { return; }
        index_ = new Dictionary<string, int>();
        for (int i = 0; i < Rows.GetLength(0); ++i) { index_[Rows[i, 0]] = i; }
    }

    // 英語の原文に対応する中国語。無ければ null。traditional=true で繁体字。
    // scope を渡すと「scope|英語」の行を先に探す（同じ英語が画面ごとに別の意味になる場合）。
    public static string Zh(string en, bool traditional, string scope = null)
    {
        if (string.IsNullOrEmpty(en)) { return null; }
        Ensure();
        int i;
        if (scope != null && index_.TryGetValue(scope + "|" + en, out i)) { return Rows[i, traditional ? 2 : 1]; }
        return index_.TryGetValue(en, out i) ? Rows[i, traditional ? 2 : 1] : null;
    }

    // 配列版。無い欄は空文字（実行時は空なら英語を出す）。missing に漏れた原文を足す。
    public static string[] ZhArray(string[] en, bool traditional, List<string> missing, string scope = null)
    {
        if (en == null) { return null; }
        var zh = new string[en.Length];
        for (int i = 0; i < en.Length; ++i)
        {
            var s = Zh(en[i], traditional, scope);
            if (s == null && !string.IsNullOrEmpty(en[i]) && missing != null) { missing.Add(en[i]); }
            zh[i] = s ?? "";
        }
        return zh;
    }
