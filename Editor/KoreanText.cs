    // 英語の原文に対応する韓国語。無ければ null。
    // scope を渡すと「scope|英語」の行を先に探す（同じ英語が画面ごとに別の意味になる場合）。
    public static string Ko(string en, string scope = null)
    {
        if (string.IsNullOrEmpty(en)) { return null; }
        string ko;
        if (scope != null && Table.TryGetValue(scope + "|" + en, out ko)) { return ko; }
        return Table.TryGetValue(en, out ko) ? ko : null;
    }

    // 配列版。無い欄は空文字（実行時は空なら英語を出す）。missing に漏れた原文を足す。
    public static string[] KoArray(string[] en, List<string> missing, string scope = null)
    {
        if (en == null) { return null; }
        var ko = new string[en.Length];
        for (int i = 0; i < en.Length; ++i)
        {
            var s = Ko(en[i], scope);
            if (s == null && !string.IsNullOrEmpty(en[i]) && missing != null) { missing.Add(en[i]); }
            ko[i] = s ?? "";
        }
        return ko;
    }
